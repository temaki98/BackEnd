# git init: Cria um novo repositório na sua pasta atual.
# git clone <url>: Copia um repositório existente para o seu computador.
# git status: Mostra o estado atual dos arquivos (modificados, prontos ou não rastreados).## git add <arquivo> ou git add .: Prepara as alterações dos arquivos para salvar.
# git commit -m "mensagem": Salva as alterações preparadas no histórico local.
# git push: Envia seus commits locais para o repositório remoto.
# git pull: Baixa e junta as novidades do repositório remoto com o seu código atual.
# git branch: Lista, cria ou apaga ramos (branches) do projeto.
# git checkout <branch> ou git switch <branch>: Muda de um ramo para outro.
# git merge <branch>: Junta o código de outro ramo no seu ramo atual
# git push origin <branch>: Solicita o push para o repositório do administrador.
